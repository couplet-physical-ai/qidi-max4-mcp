"""Reading a slicer's header locally, the way the master queue does before dispatch.

The parser is the queue's *first* opinion about what a file needs; the printer's
own metadata is re-read after upload and disagreement aborts the start. So the
tests here are about never claiming more than the header says, and about refusing
the inputs a hostile or broken file could present: a zip that lies about a
member's size, several plates, a DOCTYPE, a project with no G-code at all.
"""

from __future__ import annotations

import io
import zipfile

import pytest

from qidi_mcp.slicer_meta import (
    HEAD_BYTES,
    UnreadableSlicerFile,
    filament_summary,
    gcode_3mf_metadata,
    gcode_metadata,
    local_metadata,
    parse_gcode_header,
)

QIDISLICER = b"""; generated by QIDISlicer 1.7.0 on 2026-10-30 at 14:02:11 UTC
; estimated printing time (normal mode) = 1h 37m 12s
; filament used [mm] = 3821.4
; filament used [g] = 11.4
; first_layer_bed_temperature = 60
; first_layer_temperature = 220
; layer_height = 0.2
; nozzle_diameter = 0.4
G28
M104 S220
"""

QIDISLICER_TAIL = b"""
; SETTING_ block
; filament_colour = #1A1A1A
; filament_type = PETG
; temperature = 240
; chamber_temperature = 0
"""

ORCA = b"""; HEADER_BLOCK_START
; generated by OrcaSlicer 2.2.0 on 2026-10-31 at 09:11:00
; total estimated time: 2h 5m 30s
; filament_type = PLA;PETG
; filament_colour = #FFFFFF;#0000FF
; nozzle_temperature_initial_layer = 215,240
; hot_plate_temp_initial_layer = 60
; HEADER_BLOCK_END
G28
"""


def test_a_qidislicer_header_is_read_from_both_ends():
    meta = parse_gcode_header(QIDISLICER, QIDISLICER_TAIL)
    assert meta["source"] == "local" and meta["format"] == "gcode"
    assert meta["filament_type"] == "PETG"
    assert meta["filament_colors"] == ["#1A1A1A"]
    assert meta["filament_temps"] == [240.0]
    assert meta["estimated_time"] == 5832.0
    assert meta["first_layer_bed_temp"] == 60.0
    assert meta["first_layer_extr_temp"] == 220.0
    assert meta["layer_height"] == 0.2
    assert meta["filament_total"] == 3821.4
    assert meta["filament_weight_total"] == 11.4
    assert meta["slicer"] == "QIDISlicer" and meta["slicer_version"] == "1.7.0"


def test_an_orca_header_keeps_every_filament_in_order():
    meta = gcode_metadata(ORCA)
    assert meta["filament_type"] == "PLA;PETG"
    assert meta["filament_colors"] == ["#FFFFFF", "#0000FF"]
    assert meta["estimated_time"] == 7530.0
    assert meta["first_layer_extr_temp"] == 215.0  # first extruder, as Moonraker reports it
    assert meta["slicer"] == "OrcaSlicer"


def test_a_multi_extruder_profile_that_uses_one_filament_is_a_single_tool_file():
    """Review finding: PrusaSlicer-family profiles list every configured
    filament, so a one-colour print from a two-extruder profile looked
    multi-tool and could only ever run pinned. The per-extruder usage says which
    tools the file actually uses."""
    from qidi_mcp.printfit import wanted_filaments

    data = (b"; filament_type = PLA;PETG\n; filament_colour = #FFFFFF;#0000FF\n"
            b"; filament used [mm] = 3821.4, 0\n; filament used [g] = 11.4, 0\nG28\n")
    meta = gcode_metadata(data)
    assert meta["referenced_tools"] == [0]
    assert meta["filament_total"] == 3821.4
    assert [w["type"] for w in wanted_filaments(meta)] == ["PLA"]
    both = gcode_metadata(b"; filament_type = PLA;PETG\n; filament used [mm] = 100, 200\n")
    assert both["referenced_tools"] == [0, 1]
    second_only = gcode_metadata(b"; filament_type = PLA;PETG\n; filament used [g] = 0, 4.5\n")
    assert second_only["referenced_tools"] == [1]
    assert [w["type"] for w in wanted_filaments(second_only)] == ["PETG"]
    assert "referenced_tools" not in gcode_metadata(b"; filament_type = PLA\n; filament used [mm] = 100\n")


def test_a_file_with_no_header_says_nothing_rather_than_guessing():
    meta = gcode_metadata(b"G28\nG1 X10 Y10\n")
    assert "filament_type" not in meta and "estimated_time" not in meta
    assert meta == {"source": "local", "format": "gcode"}
    assert filament_summary(meta) == "filament unknown"


def test_only_the_ends_of_a_large_file_are_read():
    """A comment buried mid-file is never seen; a 300 MB file must not be scanned."""
    middle = b"; filament_type = ABS\n"
    data = QIDISLICER + b"G1 X1\n" * (HEAD_BYTES // 6) + middle + b"G1 X2\n" * (HEAD_BYTES // 6) + QIDISLICER_TAIL
    meta = gcode_metadata(data)
    assert meta["filament_type"] == "PETG"


def test_the_summary_line_names_material_and_colour():
    assert filament_summary({"filament_type": "PETG", "filament_colors": ["#000000"]}) == "PETG · black"
    assert filament_summary({"filament_type": "PLA;PETG"}) == "PLA;PETG (2 filaments)"


# --- .gcode.3mf -------------------------------------------------------------------


def _archive(members: dict[str, bytes]) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as zf:
        for name, data in members.items():
            zf.writestr(name, data)
    return buf.getvalue()


SLICE_INFO = b"""<?xml version="1.0" encoding="UTF-8"?>
<config>
  <plate>
    <metadata key="index" value="1"/>
    <metadata key="prediction" value="5832"/>
    <metadata key="weight" value="11.4"/>
    <filament id="1" tray_info_idx="GFL99" type="PETG" color="#1A1A1A" used_m="1.27" used_g="3.80"/>
  </plate>
</config>
"""


def test_a_3mf_reads_the_plate_header_and_fills_in_from_slice_info():
    data = _archive({
        "Metadata/plate_1.gcode": b"; generated by QIDISlicer 1.7.0 on x\nG28\n",
        "Metadata/slice_info.config": SLICE_INFO,
        "3D/3dmodel.model": b"<model/>",
    })
    meta = gcode_3mf_metadata(data)
    assert meta["format"] == "gcode.3mf" and meta["source"] == "local"
    assert meta["filament_type"] == "PETG"
    assert meta["filament_colors"] == ["#1A1A1A"]
    assert meta["estimated_time"] == 5832.0
    assert meta["filament_weight_total"] == 3.8
    assert meta["slicer"] == "QIDISlicer"


def test_the_plate_header_wins_over_slice_info_when_both_speak():
    data = _archive({
        "Metadata/plate_1.gcode": b"; filament_type = PLA\n; filament_colour = #FFFFFF\n",
        "Metadata/slice_info.config": SLICE_INFO,
    })
    meta = gcode_3mf_metadata(data)
    assert meta["filament_type"] == "PLA" and meta["filament_colors"] == ["#FFFFFF"]


def test_a_project_without_sliced_gcode_is_refused():
    with pytest.raises(UnreadableSlicerFile, match="project file"):
        gcode_3mf_metadata(_archive({"3D/3dmodel.model": b"<model/>"}))


def test_several_plates_are_refused_not_guessed_between():
    data = _archive({"Metadata/plate_1.gcode": b"G28\n", "Metadata/plate_2.gcode": b"G28\n"})
    with pytest.raises(UnreadableSlicerFile, match="2 sliced plates"):
        gcode_3mf_metadata(data)
    two = SLICE_INFO.replace(b"</plate>", b"</plate><plate><metadata key='index' value='2'/></plate>")
    data = _archive({"Metadata/plate_1.gcode": b"G28\n", "Metadata/slice_info.config": two})
    with pytest.raises(UnreadableSlicerFile, match="2 plates"):
        gcode_3mf_metadata(data)


def test_a_doctype_in_the_xml_is_refused_outright():
    evil = b'<?xml version="1.0"?><!DOCTYPE x [<!ENTITY e SYSTEM "file:///etc/passwd">]><config/>'
    data = _archive({"Metadata/plate_1.gcode": b"G28\n", "Metadata/slice_info.config": evil})
    with pytest.raises(UnreadableSlicerFile, match="DOCTYPE"):
        gcode_3mf_metadata(data)


def test_a_member_that_declares_an_absurd_size_is_never_inflated(monkeypatch):
    """A zip bomb lies in its central directory; the declared size is checked first."""
    import qidi_mcp.slicer_meta as sm

    monkeypatch.setattr(sm, "MAX_3MF_MEMBER_BYTES", 10)
    data = _archive({"Metadata/plate_1.gcode": b"; filament_type = PLA\n" * 4})
    with pytest.raises(UnreadableSlicerFile, match="will not inflate"):
        gcode_3mf_metadata(data)


def test_not_a_zip_is_said_plainly():
    with pytest.raises(UnreadableSlicerFile, match="Not a zip"):
        gcode_3mf_metadata(b"G28\n")


# --- dispatch by suffix ----------------------------------------------------------------


def test_local_metadata_dispatches_on_the_suffix():
    assert local_metadata("part.gcode", QIDISLICER)["format"] == "gcode"
    assert local_metadata("part.GCODE.3MF", _archive({"Metadata/plate_1.gcode": b"G28\n"}))["format"] == "gcode.3mf"
    with pytest.raises(UnreadableSlicerFile, match="not a format"):
        local_metadata("part.3mf", b"PK")
    with pytest.raises(UnreadableSlicerFile):
        local_metadata("part.stl", b"solid")
