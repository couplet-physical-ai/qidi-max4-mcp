def local_metadata(filename: str, data: bytes) -> dict[str, Any]:
    """Slicer metadata for a file the queue holds, by its suffix.

    Unknown suffixes are refused rather than guessed at: a file this cannot read
    is a file whose filament needs are unknown, and "unknown" is a verdict the
    dispatcher treats as not fit to start unattended.
    """
    low = filename.lower()
    if low.endswith(".gcode.3mf"):
        return gcode_3mf_metadata(data)
    if low.endswith((".gcode", ".g", ".gco", ".nc")):
        return gcode_metadata(data)
    raise UnreadableSlicerFile(
        f"{filename!r} is not a format the master queue can read.",
        hint="Queue a .gcode or a sliced .gcode.3mf.",
    )


def filament_summary(meta: Mapping[str, Any]) -> str:
    """One line for a queue row: ``PETG · black`` / ``PLA;PETG (2 filaments)``."""
    types = [t for t in str(meta.get("filament_type") or "").split(";") if t]
    colors = meta.get("filament_colors") or []
    if not types:
        return "filament unknown"
    if len(types) == 1:
        from .filament_names import nearest_color_word

        word = nearest_color_word(colors[0]) if colors else None
        return f"{types[0]} · {word}" if word else types[0]
    return f"{';'.join(types)} ({len(types)} filaments)"
