"""Read a slicer's header locally, before the file is anywhere near a printer.

The master queue keeps files centrally and picks a printer for each one by the
filament it needs. That decision has to be made *before* the file is uploaded --
uploading to every printer so Moonraker can parse the metadata would spray
megabytes at three machines for one print -- so the queue needs its own reader
for the two formats the lab produces:

* ``.gcode`` from QIDISlicer, PrusaSlicer and OrcaSlicer, whose ``; key = value``
  comments sit at the top (settings) and the bottom (the ``; SETTING_`` block);
* ``.gcode.3mf``, the format QIDI's own slicer and screen write: a zip whose
  ``Metadata/plate_1.gcode`` carries the same header, plus
  ``Metadata/slice_info.config`` describing each plate's filaments.

What comes out uses **Moonraker's key names** (``filament_type``,
``filament_colors``, ``estimated_time`` ...) so :mod:`qidi_mcp.printfit` can take
either source without a translation layer, and every result is stamped
``source="local"`` so nothing downstream mistakes it for what the printer itself
said. The dispatcher re-reads the printer's own metadata after upload and aborts
on disagreement; this module is the *first* opinion, never the last.

Deliberately bounded and suspicious of its input:

* a ``.gcode`` is read from its head and tail only (``HEAD_BYTES``/``TAIL_BYTES``),
  never whole -- a 300 MB file must not be decoded to find one comment line;
* a ``.gcode.3mf`` member's *declared* size is checked before it is read, so a
  tiny archive declaring a gigabyte plate is refused rather than inflated;
* an archive with several plates is refused: Moonraker prints one plate, and
  which one is a question this module must not answer by guessing;
* any ``<!DOCTYPE`` in the XML is refused outright, which is simpler than
  trusting a parser's entity handling.

Pure functions over bytes; the file I/O is the caller's.
"""

from __future__ import annotations

import io
import re
import zipfile
from collections.abc import Mapping
from typing import Any
from xml.etree import ElementTree

from .errors import InvalidRequest

#: How much of a ``.gcode`` is inspected at each end. PrusaSlicer-family headers
#: are a few KB; the trailing ``; SETTING_`` block on a QIDISlicer file with many
#: filaments is well under 64 KB. Doubling that costs nothing and buys margin.
HEAD_BYTES = 128 * 1024
TAIL_BYTES = 128 * 1024

#: Largest archive member this will inflate. A plate's G-code header is in its
#: first kilobytes, so the member is read only up to ``HEAD_BYTES`` anyway; the
#: cap is on what the zip *declares*, which is what a zip bomb lies about.
MAX_3MF_MEMBER_BYTES = 2_000_000_000

_KV = re.compile(r"^;\s*([A-Za-z0-9_ \[\]()/]+?)\s*[=:]\s*(.*?)\s*$")
_DURATION = re.compile(r"(?:(\d+)\s*d)?\s*(?:(\d+)\s*h)?\s*(?:(\d+)\s*m)?\s*(?:(\d+)\s*s)?$")
_GENERATED = re.compile(r"^;\s*generated by\s+(\S+)\s+([^\s]+)", re.IGNORECASE)
_PLATE_MEMBER = re.compile(r"^Metadata/plate_(\d+)\.gcode$")


class UnreadableSlicerFile(InvalidRequest):
    """The file cannot be read well enough to say what it would print."""

    code = "slicer_file_unreadable"


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def _split(value: str) -> list[str]:
    return [p.strip() for p in re.split(r"[;,]", value) if p.strip()]


def _num(value: Any) -> float | None:
    try:
        out = float(str(value).strip().split(";")[0].split(",")[0])
    except (TypeError, ValueError):
        return None
    return out if out == out else None  # NaN is not a number worth keeping


def _duration_s(value: str) -> float | None:
    """``1h 37m 12s`` / ``2d 1h`` / ``5820`` -> seconds."""
    text = value.strip().lower()
    if not text:
        return None
    if re.fullmatch(r"\d+(\.\d+)?", text):
        return float(text)
    m = _DURATION.fullmatch(text)
    if not m or not any(m.groups()):
        return None
    d, h, mi, s = (int(g) if g else 0 for g in m.groups())
    return float(d * 86400 + h * 3600 + mi * 60 + s)


def _hex_list(value: str) -> list[str]:
    out = []
    for part in _split(value):
        p = part.lstrip("#").upper()
        if re.fullmatch(r"[0-9A-F]{6}", p):
            out.append("#" + p)
        elif re.fullmatch(r"[0-9A-F]{8}", p):
            out.append("#" + p[:6])  # Orca sometimes writes RRGGBBAA
    return out


def _decode(blob: bytes) -> str:
    return blob.decode("utf-8", errors="replace")


# ---------------------------------------------------------------------------
# .gcode
# ---------------------------------------------------------------------------


def parse_gcode_header(head: bytes, tail: bytes = b"") -> dict[str, Any]:
    """Slicer facts from the comment lines of a ``.gcode``, Moonraker-shaped.

    Only ``;``-comment lines are read; a G-code line is never interpreted. Both
    ends are scanned because PrusaSlicer-family slicers put the summary at the top
    and the full settings dump at the bottom, and QIDISlicer's ``filament_type``
    lives in the dump.
    """
    found: dict[str, str] = {}
    slicer: tuple[str, str] | None = None
    for blob in (head, tail):
        for raw in _decode(blob).splitlines():
            line = raw.strip()
            if not line.startswith(";"):
                continue
            g = _GENERATED.match(line)
            if g and slicer is None:
                slicer = (g.group(1), g.group(2))
                continue
            m = _KV.match(line)
            if not m:
                continue
            key = m.group(1).strip().lower()
            # First occurrence wins (the header), so the settings dump at the
            # bottom cannot override what the summary said -- except for keys the
            # summary never carries, which the dump fills in.
            found.setdefault(key, m.group(2))

    meta: dict[str, Any] = {"source": "local", "format": "gcode"}

    def first(*keys: str) -> str | None:
        for k in keys:
            if k in found and found[k] != "":
                return found[k]
        return None

    types = first("filament_type")
    if types:
        meta["filament_type"] = ";".join(_split(types))
    colors = first("filament_colour", "filament_color", "extruder_colour", "extruder_color")
    if colors:
        hexes = _hex_list(colors)
        if hexes:
            meta["filament_colors"] = hexes
    temps = first("temperature", "nozzle_temperature")
    if temps:
        parsed = [t for t in (_num(p) for p in _split(temps)) if t is not None]
        if parsed:
            meta["filament_temps"] = parsed

    est = first(
        "estimated printing time (normal mode)",
        "estimated printing time",
        "total estimated time",
        "model printing time",
        "print_time",
    )
    if est is not None:
        seconds = _duration_s(est)
        if seconds is not None:
            meta["estimated_time"] = seconds
    # Per-extruder usage ("filament used [mm] = 3821.4, 0") is how a
    # PrusaSlicer-family file says which of its configured filaments the print
    # actually uses: the profile lists every extruder, the usage lists the ones
    # with toolpaths. Moonraker's referenced_tools is the same fact read from
    # the T-commands; without it a one-colour print from a two-extruder profile
    # would look multi-tool and could only ever run pinned.
    for key, names in (("filament_total", ("filament used [mm]",)),
                       ("filament_weight_total", ("filament used [g]", "total filament used [g]"))):
        raw = first(*names)
        if raw is None:
            continue
        values = [v for v in (_num(p) for p in _split(raw)) if v is not None]
        if not values:
            continue
        meta[key] = round(sum(values), 3)
        if len(values) > 1 and "referenced_tools" not in meta:
            meta["referenced_tools"] = [i for i, v in enumerate(values) if v > 0]
    for key, names in (
        ("first_layer_bed_temp", ("first_layer_bed_temperature", "hot_plate_temp_initial_layer",
                                  "textured_plate_temp_initial_layer")),
        ("first_layer_extr_temp", ("first_layer_temperature", "nozzle_temperature_initial_layer")),
        ("layer_height", ("layer_height",)),
        ("nozzle_diameter", ("nozzle_diameter",)),
        ("chamber_temp", ("chamber_temperature", "chamber_temperatures")),
    ):
        raw = first(*names)
        if raw is None:
            continue
        # Per-extruder lists ("60,60") collapse to the first value, as Moonraker does.
        value = _num(raw)
        if value is not None:
            meta[key] = value
    if slicer:
        meta["slicer"], meta["slicer_version"] = slicer
    return meta


def gcode_metadata(data: bytes) -> dict[str, Any]:
    """:func:`parse_gcode_header` over a whole file's bytes, reading only its ends."""
    head = data[:HEAD_BYTES]
    tail = data[-TAIL_BYTES:] if len(data) > HEAD_BYTES else b""
    return parse_gcode_header(head, tail)


# ---------------------------------------------------------------------------
# .gcode.3mf
# ---------------------------------------------------------------------------


def _slice_info(xml_bytes: bytes) -> dict[str, Any]:
    """Filaments and the time estimate from ``Metadata/slice_info.config``.

    The format is QIDI/Bambu's: ``<config><plate><metadata key=.. value=../>
    <filament id=.. type=.. color=.. used_m=.. used_g=../>...</plate></config>``.
    """
    if b"<!DOCTYPE" in xml_bytes.upper():
        raise UnreadableSlicerFile(
            "The archive's slice_info.config carries a DOCTYPE, which a slicer never writes.",
            hint="Re-export the file from the slicer.",
        )
    try:
        root = ElementTree.fromstring(xml_bytes)
    except ElementTree.ParseError as exc:
        raise UnreadableSlicerFile(f"slice_info.config is not well-formed XML: {exc}") from exc
    plates = root.findall("plate")
    if len(plates) > 1:
        raise UnreadableSlicerFile(
            f"The archive holds {len(plates)} plates; the master queue prints one plate per file.",
            hint="Export each plate as its own .gcode.3mf.",
        )
    out: dict[str, Any] = {}
    if not plates:
        return out
    plate = plates[0]
    types, colors, weight = [], [], 0.0
    for fil in plate.findall("filament"):
        types.append((fil.get("type") or "").strip())
        colors.append((fil.get("color") or "").strip())
        g = _num(fil.get("used_g"))
        if g:
            weight += g
    if any(types):
        out["filament_type"] = ";".join(t or "?" for t in types)
    hexes = _hex_list(";".join(colors))
    if hexes:
        out["filament_colors"] = hexes
    if weight:
        out["filament_weight_total"] = round(weight, 2)
    for md in plate.findall("metadata"):
        if md.get("key") == "prediction":
            seconds = _num(md.get("value"))
            if seconds:
                out["estimated_time"] = seconds
        if md.get("key") == "weight" and "filament_weight_total" not in out:
            g = _num(md.get("value"))
            if g:
                out["filament_weight_total"] = g
    return out


def gcode_3mf_metadata(data: bytes) -> dict[str, Any]:
    """Slicer facts from a ``.gcode.3mf``.

    The plate's G-code header is the primary source (same parser as ``.gcode``);
    ``slice_info.config`` fills in what the header lacks and is where a
    multi-plate archive is detected.
    """
    try:
        zf = zipfile.ZipFile(io.BytesIO(data))
    except zipfile.BadZipFile as exc:
        raise UnreadableSlicerFile(
            "Not a zip archive, so not a .gcode.3mf.",
            hint="A bare .3mf project without sliced G-code cannot be printed either.",
        ) from exc
    with zf:
        members = {info.filename: info for info in zf.infolist()}
        for info in members.values():
            if info.file_size > MAX_3MF_MEMBER_BYTES or info.file_size < 0:
                raise UnreadableSlicerFile(
                    f"Archive member {info.filename!r} declares {info.file_size} bytes, "
                    "which this reader will not inflate."
                )
        plates = sorted(
            (int(m.group(1)), name) for name in members if (m := _PLATE_MEMBER.match(name))
        )
        if not plates:
            raise UnreadableSlicerFile(
                "The archive holds no Metadata/plate_N.gcode, so it is a project file, "
                "not sliced G-code.",
                hint="Export a sliced .gcode.3mf (or a .gcode) from the slicer.",
            )
        if len(plates) > 1:
            raise UnreadableSlicerFile(
                f"The archive holds {len(plates)} sliced plates; the master queue prints "
                "one plate per file.",
                hint="Export each plate as its own .gcode.3mf.",
            )
        _, plate_name = plates[0]
        with zf.open(plate_name) as fh:
            head = fh.read(HEAD_BYTES)
        meta = parse_gcode_header(head)
        meta["format"] = "gcode.3mf"
        meta["plate"] = plate_name
        if "Metadata/slice_info.config" in members:
            with zf.open("Metadata/slice_info.config") as fh:
                info = _slice_info(fh.read(HEAD_BYTES))
            for key, value in info.items():
                meta.setdefault(key, value)
    return meta


